    private void entrarBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_entrarBtnActionPerformed
        // TODO add your handling code here:                                     
        String nome = usuarioTextFieldInput.getText();
        String senha = senhaTextFieldInput.getText(); 

        if (nome.isEmpty() || senha.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Preencha todos os campos!");
            return;
        }

        UsuarioDAO dao = new UsuarioDAO();

        if (dao.autenticar(nome, senha)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Login bem-sucedido!");
            new TelaPrincipal().setVisible(true);
            this.dispose(); // Fecha tela de login
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Usuário ou senha inválidos.");
        }
    
    }//GEN-LAST:event_entrarBtnActionPerformed

